#!/usr/bin/env node
/*
  scripts/collect-audio-texts.js — collects every English string that the app actually
  hands to Audio.speak() from a high-confidence, exactly-reproducible source (vocabulary,
  concept examples, conversations, reading articles, alphabet letters), so we can pre-render
  real human audio for it with Piper TTS instead of relying on the browser's speechSynthesis.

  Deliberately NOT exhaustive: ad-hoc English snippets embedded inside Hebrew exercise text
  (via {curly braces}) are too varied to enumerate reliably here, and gracefully fall back to
  the browser's own TTS at runtime (see script.js Audio.speak) if no pre-rendered clip exists
  — so under-collecting here is safe, just less coverage, never a bug.

  Usage: node scripts/collect-audio-texts.js > scripts/audio-gen/texts.json
*/
const path = require("path");
const { loadCurriculum } = require("./load-curriculum.js");

const C = loadCurriculum();
const texts = new Set();

// Vocabulary: word + its example sentence (exactly as script.js speaks them, unmodified)
C.vocabulary.forEach(v => {
  if (v.word) texts.add(v.word);
  if (v.exampleSentence) texts.add(v.exampleSentence);
});

// Concept examples: mirrors script.js's `sayButtons(e[2] || e[0].replace(" — ", ", "))`
C.concepts.forEach(c => {
  (c.examples || []).forEach(e => {
    texts.add(e[2] || String(e[0]).replace(" — ", ", "));
  });
});

// Conversations: NPC lines (skip stage directions in parens) + every choice's English reply
C.conversations.forEach(s => {
  Object.values(s.nodes).forEach(n => {
    if (n.npc && !/^\(/.test(n.npc)) texts.add(n.npc);
    (n.choices || []).forEach(c => { if (c.en) texts.add(c.en); });
  });
});

// Reading articles
delete require.cache[require.resolve(path.join(__dirname, "..", "curriculum", "articles.js"))];
global.ARTICLES = undefined;
require(path.join(__dirname, "..", "curriculum", "articles.js"));
(global.ARTICLES || []).forEach(a => {
  a.paragraphs.forEach(p => p.forEach(([en]) => { if (en) texts.add(en); }));
});

// Alphabet: spoken letter names + the "Ay, apple" style example already generated by pre-a1.js's
// letterNote() into concept-like note objects — but those live in lesson.notes, not C.concepts,
// so pull them directly off the lessons.
C.lessons.forEach(l => {
  (l.notes || []).forEach(note => {
    (note.examples || []).forEach(e => { texts.add(e[2] || String(e[0]).replace(" — ", ", ")); });
  });
});

process.stdout.write(JSON.stringify(Array.from(texts).sort(), null, 0));
process.stderr.write("Collected " + texts.size + " unique strings.\n");
